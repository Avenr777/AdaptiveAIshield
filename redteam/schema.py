"""
Core data models for the AIShield Red Team attack generator.

These types are the contract between the Red Team (this package) and the
Blue Team firewall: every attack the generator produces conforms to
`Attack`, and every round of benchmarking produces a `GenerationBatch`
that the Blue Team evaluates and reports back on via `AttackResult`.
"""

from __future__ import annotations

import uuid
import time
from dataclasses import dataclass, field
from enum import Enum
from typing import List, Optional, Dict, Any


class AttackCategory(str, Enum):
    DIRECT_OVERRIDE = "direct_instruction_override"
    ROLEPLAY_PERSONA = "roleplay_persona_hijacking"
    OBFUSCATION_ENCODING = "obfuscation_encoding"
    INDIRECT_INJECTION = "indirect_injection"
    MULTI_TURN_ESCALATION = "multi_turn_escalation"
    CONTEXT_POISONING = "context_memory_poisoning"
    TOOL_ABUSE = "tool_function_call_abuse"


class AttackSource(str, Enum):
    SEED = "seed"                # hand-written seed template
    DATASET = "dataset"          # pulled from a public jailbreak-prompt dataset
    LLM_GENERATED = "llm"        # freshly generated by the attacker LLM
    MUTATED = "mutated"          # programmatic mutation of a prior attack
    CROSSOVER = "crossover"      # recombination of two prior attacks


@dataclass
class Attack:
    """
    A single attack candidate. `turns` holds one string for single-turn
    attacks, or multiple strings (in order) for multi-turn escalation
    attacks — the Blue Team should replay them as successive user turns
    in the same conversation.
    """
    category: AttackCategory
    turns: List[str]
    source: AttackSource
    technique_notes: str = ""
    id: str = field(default_factory=lambda: uuid.uuid4().hex[:12])
    parent_ids: List[str] = field(default_factory=list)
    generation: int = 0
    created_at: float = field(default_factory=time.time)
    metadata: Dict[str, Any] = field(default_factory=dict)
    mutation_depth: int = 0

    def to_dict(self) -> Dict[str, Any]:
        d = dict(self.__dict__)
        d["category"] = self.category.value
        d["source"] = self.source.value
        return d

    @staticmethod
    def from_dict(d: Dict[str, Any]) -> "Attack":
        d = dict(d)
        d["category"] = AttackCategory(d["category"])
        d["source"] = AttackSource(d["source"])
        d.setdefault("mutation_depth", 0)
        return Attack(**d)


@dataclass
class GenerationBatch:
    round_number: int
    attacks: List[Attack]
    created_at: float = field(default_factory=time.time)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "round_number": self.round_number,
            "created_at": self.created_at,
            "attacks": [a.to_dict() for a in self.attacks],
        }


@dataclass
class AttackResult:
    """
    Filled in by whatever evaluates the attack against the Blue Team
    firewall. `evaded` = True means the attack was Allowed when it
    should have been Warned or Blocked (i.e. the attack succeeded).
    """
    attack_id: str
    decision: str          # "allow" | "warn" | "block"
    risk_score: Optional[float]
    evaded: bool
    notes: str = ""
